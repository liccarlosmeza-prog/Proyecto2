function almacen(){const m=new Map();return {getItem:k=>m.get(k)??null,setItem:(k,v)=>m.set(k,String(v)),removeItem:k=>m.delete(k)};}
function preparar(){globalThis.localStorage=almacen();globalThis.sessionStorage=almacen();globalThis.window=new EventTarget();}
const titular={id:'t1',vivienda:'A-07',calle:'Magallanes',numero:'78',interior:'1C',tipo:'Titular',estatus:'Rentada',privacidad:true};
test('IDs vecinales por domicilio, sufijo y validación de componentes',()=>{
 assert.equal(idVecino(titular),'Maga781CTit');
 assert.equal(idVecino({...titular,tipo:'Arrendatario'}),'Maga781CRen');
 assert.equal(idVecino({...titular,calle:'Árboles',interior:''}),'Arbo78Tit');
 assert.throws(()=>idVecino({...titular,numero:'N/A'}));
});
test('alta pendiente del Auxiliar, autorización de Presidencia y reinicio limitado',async()=>{
 preparar();const a=crearServicioAcceso(),clave='Inicial-demo-2026',nueva='Vecino-nueva-2026';
 await a.configurar(clave);
 await assert.rejects(a.configurar(clave),/ya fue/);
 assert.ok(!localStorage.getItem('robles_u4_cuentas').includes(clave));
 await assert.rejects(a.iniciar('PRES-001','incorrecta'));
 await a.iniciar('PRES-001',clave);
 await a.asignar('AUX-001',clave);await a.asignar('TES-001',clave);
 await a.iniciar('TES-001',clave);
 await assert.rejects(a.registrarResidente(titular),/Solo Presidencia/);
 await a.iniciar('AUX-001',clave);
 const pendiente=await a.registrarResidente(titular);
 assert.deepEqual(pendiente,{id:'Maga781CTit',clave:null,pendiente:true});
 await assert.rejects(a.autorizar(titular.id),/Solo Presidencia/);
 await assert.rejects(a.asignar(pendiente.id,nueva),/No puedes/);
 await assert.rejects(a.asignar('TES-001',nueva),/No puedes/);
 await assert.rejects(a.iniciar(pendiente.id,clave));
 await a.iniciar('PRES-001',clave);
 const autorizado=await a.autorizar(titular.id);
 assert.equal(autorizado.id,pendiente.id);
 const arrendatario=await a.registrarResidente({...titular,id:'r1',tipo:'Arrendatario'});
 assert.equal(arrendatario.id,'Maga781CRen');assert.equal(arrendatario.pendiente,false);
 await assert.rejects(a.registrarResidente({...titular,id:'duplicado',vivienda:'B-01',calle:'Magallana'}),/Ya existe/);
 await assert.rejects(a.autorizar(titular.id));
 await a.iniciar(autorizado.id.toLowerCase(),autorizado.clave);
 const sesionAnterior=sessionStorage.getItem('robles_u4_sesion');
 await assert.rejects(a.asignar(autorizado.id,nueva),/Solo Presidencia/);
 await a.iniciar('AUX-001',clave);await a.asignar(autorizado.id,nueva);
 sessionStorage.setItem('robles_u4_sesion',sesionAnterior);
 assert.equal(a.sesion(),null);
 await assert.rejects(a.iniciar(autorizado.id,autorizado.clave));
 await a.iniciar(autorizado.id,nueva);
 const residentes=JSON.parse(localStorage.getItem('los_robles_residentes'));
 localStorage.setItem('los_robles_residentes',JSON.stringify(residentes.map(r=>r.id===titular.id?{...r,estatus:'Inactiva'}:r)));
 assert.equal(a.sesion(),null);
 assert.equal((await a.iniciar(arrendatario.id,arrendatario.clave)).vivienda,titular.vivienda);
});
